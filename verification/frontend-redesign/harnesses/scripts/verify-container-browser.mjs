    assert.equal(await member.getByRole('button',{name:'People & access'}).count(),0)
    await member.getByRole('button',{name:renamedName,exact:true}).waitFor()
    assert.equal(await member.getByRole('button',{name:'one-gib-verified.bin',exact:true}).count(),0)
    assert.equal((await memberContext.request.get(url+'/api/files/content?path='+encodeURIComponent('/'+renamedName))).status(),403)
    assert.equal((await memberContext.request.get(url+'/api/files?path='+encodeURIComponent('/../'))).status(),400)
    assert.equal((await memberContext.request.get(url+'/api/admin/users')).status(),403)
    await member.getByRole('button',{name:'Account settings'}).click()
    await member.getByText('Your password',{exact:true}).waitFor()
    await member.screenshot({path:join(screenshots,'15-member-account-settings.png'),fullPage:true})
    check('scoped member sees only their root; download, upload, traversal, and administration denied')
