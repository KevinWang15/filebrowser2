    await member.getByRole('heading',{name:'Good to see you again.'}).waitFor()
    await memberContext.close()
    check('disabling a member immediately revokes their browser session')

    await page.getByRole('button',{name:'Edit admin'}).click()
    await page.getByLabel('Role').selectOption('user')
    await page.getByRole('button',{name:'Save changes'}).click()
    await page.getByText('Keep at least one enabled administrator').waitFor()
    await shot('16-last-admin-protection')
    await page.getByRole('button',{name:'Close dialog'}).click()
    check('last administrator cannot be demoted')
    await page.getByRole('button',{name:'Activity',exact:true}).click()
    await page.locator('.activity-list').waitFor()
    assert.match(await page.locator('.activity-list').textContent(),/finished an upload/)
    await shot('17-workspace-activity')
    await page.getByRole('button',{name:'Settings',exact:true}).click()
    await page.getByText('100 KiB',{exact:true}).waitFor()
    await shot('18-runtime-configuration')
    check('settings display the actual runtime chunk override')
    await page.getByRole('button',{name:'My files',exact:true}).first().click()
    await page.getByRole('button',{name:'My files',exact:true}).last().click()
    await page.getByRole('button',{name:'one-gib-verified.bin',exact:true}).waitFor()
    await shot('19-one-gib-file-in-workspace')
    await page.setViewportSize({width:390,height:844})
    await shot('20-mobile-workspace')
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true)
    for(const label of ['My files','Transfers','People & access','Activity','Settings'])assert.equal(await page.getByRole('button',{name:label,exact:true}).first().isVisible(),true)
    check('mobile viewport has no page overflow and all navigation remains accessible')
    await page.setViewportSize({width:1440,height:980})
    await page.getByRole('button',{name:'Settings',exact:true}).click()
    await page.getByLabel('Current password').fill('container-verification-password')
    await page.getByLabel('New password').fill('changed-container-verification-password')
